CREATE   PROCEDURE dbo.SP_Coupon_ValidateAndApply
(
    @CouponId BIGINT,
    @UserId BIGINT,
    @CartId BIGINT = NULL,
    @SubTotal DECIMAL(18,2),

    @Recalculate BIT = 1,           -- 1=compute amount, 0=trust incoming amount
    @SyncCart BIT = 0,              -- if invalid, clear cart coupon
    @SyncCheckout BIT = 0,          -- if invalid, clear checkout coupon
    @CheckoutTxnId BIGINT = NULL,

    @IsValid BIT OUTPUT,
    @CouponAmount DECIMAL(18,2) OUTPUT,
    @ErrorMessage NVARCHAR(200) OUTPUT
)
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE
        @ValidFrom DATETIME,
        @ValidTo DATETIME,
        @MinCartValue DECIMAL(18,2),
        @CouponPercentage DECIMAL(18,2),
        @FixedAmount DECIMAL(18,2);

    SET @IsValid = 0;
    SET @CouponAmount = 0;
    SET @ErrorMessage = NULL;

    SELECT
        @ValidFrom = Valid_From,
        @ValidTo = Valid_To,
        @MinCartValue = Min_Cart_Value,
        @CouponPercentage = Coupon_Percentage,
        @FixedAmount = Coupon_Amount
    FROM Tbl_Coupon_Info
    WHERE Coupon_Id = @CouponId
      AND Status = 1;

    IF @ValidFrom IS NULL
    BEGIN
        SET @ErrorMessage = 'Invalid coupon';
        GOTO INVALID;
    END

    IF GETDATE() NOT BETWEEN @ValidFrom AND @ValidTo
    BEGIN
        SET @ErrorMessage = 'Coupon expired';
        GOTO INVALID;
    END

    IF @MinCartValue IS NOT NULL AND @SubTotal < @MinCartValue
    BEGIN
        SET @ErrorMessage = 'Minimum cart value not met';
        GOTO INVALID;
    END

    IF @Recalculate = 1
    BEGIN
        IF @CouponPercentage IS NOT NULL AND @CouponPercentage > 0
            SET @CouponAmount = ROUND((@SubTotal * @CouponPercentage)/100.0, 2);
        ELSE
            SET @CouponAmount = ISNULL(@FixedAmount, 0);
    END

    SET @IsValid = 1;
    RETURN;

INVALID:
    IF @SyncCart = 1 AND @CartId IS NOT NULL
    BEGIN
        UPDATE Cart
        SET Has_Promo_Code = 0,
            Promo_Code_ID = NULL,
            Promo_Code_Amount = NULL,
            UpdatedOn = SYSDATETIME()
        WHERE CartId = @CartId;
    END

    IF @SyncCheckout = 1 AND @CheckoutTxnId IS NOT NULL
    BEGIN
        UPDATE CheckOutPaymentTransactions
        SET Has_Promo_Code = 0,
            Promo_Code_ID = NULL,
            Promo_Code_Amount = NULL,
            UpdatedOn = SYSDATETIME()
        WHERE PaymentTransactionId = @CheckoutTxnId;
    END
END
