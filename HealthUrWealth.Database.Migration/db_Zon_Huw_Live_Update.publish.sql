        -- 1. Validate Checkout
        --------------------------------------------------
        SELECT
            @CouponId = Promo_Code_ID,
            @CouponAmount = ISNULL(Promo_Code_Amount, 0),
            @HasPromo = ISNULL(Has_Promo_Code, 0),
            @ShippingCharges = ISNULL(ShippingCharges, 0)
        FROM CheckOutPaymentTransactions
        WHERE PaymentTransactionId = @CheckoutTxnId
          AND UserId = @UserId
          AND OrderStatus = 'Open';

        IF @@ROWCOUNT = 0
        BEGIN
            RAISERROR ('Invalid or already processed checkout',16,1);
            ROLLBACK TRANSACTION;
            RETURN;
        END

        --------------------------------------------------
        -- 2. Subtotal
        --------------------------------------------------
        SELECT @SubTotal = SUM(ProductCost)
        FROM CheckOutUserProductTransactions
        WHERE PaymentTransactionId = @CheckoutTxnId;

        IF @SubTotal IS NULL SET @SubTotal = 0;

        --------------------------------------------------
        -- 3. Coupon via Engine
        --------------------------------------------------
        IF @CouponId IS NOT NULL AND @HasPromo = 1
        BEGIN
            EXEC dbo.SP_Coupon_ValidateAndApply
                @CouponId = @CouponId,
                @UserId = @UserId,
                @CartId = NULL,
                @SubTotal = @SubTotal,
                @Recalculate = 0,
                @SyncCart = 1,
                @SyncCheckout = 1,
                @CheckoutTxnId = @CheckoutTxnId,
                @IsValid = @IsValid OUTPUT,
                @CouponAmount = @CouponAmount OUTPUT,
                @ErrorMessage = @Err OUTPUT;

            IF @IsValid = 0
            BEGIN
                SET @CouponId = NULL;
                SET @CouponAmount = 0;
                SET @HasPromo = 0;
            END
        END

        --------------------------------------------------
        -- 4. Final Amount
        --------------------------------------------------
        SET @FinalAmount = @SubTotal + @ShippingCharges - @CouponAmount;
        IF @FinalAmount < 0 SET @FinalAmount = 0;

        --------------------------------------------------
        -- 5. Insert Payment
        --------------------------------------------------
        INSERT INTO PaymentTransactions
        (
            UserId, PaymentMode, TxnStatus, PaymentStatus, CreatedOn,
            PGTxnId, CurrencyCode, CurrencySymbol, CurrencyValue,
            TxnAmount, TxnMessage, Authorized, OrderCurrentStatus,
            ShippingCharges, Has_Promo_Code, Promo_Code_ID, Promo_Code_Amount
        )
        SELECT
            UserId,
            @PaymentMode,
            'SUCCESS',
            1,
            SYSDATETIME(),
            @GatewayTransactionId,
            CurrencyCode,
            CurrencySymbol,
            CurrencyValue,
            @FinalAmount,
            'Transaction Successful through Payment Gateway',
            1,
            6,
            @ShippingCharges,
            @HasPromo,
            @CouponId,
            CASE WHEN @HasPromo = 1 THEN @CouponAmount ELSE NULL END
        FROM CheckOutPaymentTransactions
        WHERE PaymentTransactionId = @CheckoutTxnId;

        SET @FinalPaymentTxnId = SCOPE_IDENTITY();

		--------------------------------------------------
        -- 6. Move snapshot → final order items
        --------------------------------------------------
		INSERT INTO UserProductTransactions
        (
            PaymentTransactionId,
            UserId,
            ProductId,
            SubProductId,
            Quantity,

            ProductOriginalCost,
            ProductCost,
            ProductDiscountPercentage,
            ProductDiscountCost,

            ShippingAddressId,
            BillingAddressId,
            IsActive,
            IsDeleted,
            CreatedOn,
            UpdatedOn,
            CreatedBy,
            UpdatedBy,
            Status,

            CurrencyCode,
            CurrencyValue,
            CurrencySymbol,

            OrdersReturnReason,
            OrdersReturnAction,
            ReplacementTransactionId,
            IsReplaced,

			ExpectedDeliveryDate,

			GST_Percentage,
			GST_Amount,
			CGST,
			SGST,
			IGST,
			BaseAmount
        )
		SELECT
             @FinalPaymentTxnId,
            cup.UserId,
            cup.ProductId,
            cup.SubProductId,
            cup.Quantity,

             p.ProductOriginalCost,
            cup.ProductCost,
            ISNULL(cup.ProductDiscountPercentage, 0),
            ISNULL(cup.ProductDiscountCost, 0),

            cup.ShippingAddressId,
            cup.BillingAddressId,
            1,
            0,
            SYSDATETIME(),
            SYSDATETIME(),
            cup.CreatedBy,
            cup.UpdatedBy,
            0,

            chk.CurrencyCode,
            chk.CurrencyValue,
            chk.CurrencySymbol,

            cup.OrdersReturnReason,
            cup.OrdersReturnAction,
            cup.ReplacementTransactionId,
            cup.IsReplaced,

            cup.ExpectedDeliveryDate,

			p.GST,
			gst.GST_Amount,
			gst.CGST,
			gst.SGST,
			gst.IGST,
			gst.BaseAmount
		 FROM CheckOutUserProductTransactions cup
        INNER JOIN CheckOutPaymentTransactions chk
            ON chk.PaymentTransactionId = cup.PaymentTransactionId
        INNER JOIN Products p
            ON p.ProductId = cup.ProductId
        INNER JOIN UserAddresses ua
            ON ua.UserAddressId = cup.ShippingAddressId
        CROSS APPLY dbo.fn_CalculateGST(
            cup.ProductCost,
            p.GST,
            ua.StateName
        ) gst
        WHERE cup.PaymentTransactionId = @CheckoutTxnId;

		--------------------------------------------------
        -- 7. Close checkout
        --------------------------------------------------
        UPDATE CheckOutPaymentTransactions
        SET OrderStatus = 'Closed',
            UpdatedOn = SYSDATETIME()
        WHERE PaymentTransactionId = @CheckoutTxnId;

		--------------------------------------------------
        -- 8. Clear Cart 
        --------------------------------------------------       
        DELETE CI
        FROM CartItem CI
        INNER JOIN Cart C ON CI.CartId = C.CartId
        WHERE C.UserId = @UserId;

        UPDATE Cart
        SET Status = 'CHECKED_OUT',
            UpdatedOn = SYSDATETIME()
        WHERE UserId = @UserId
          AND Status = 'ACTIVE';

		--------------------------------------------------
        -- 9. Attach prescriptions to order
        --------------------------------------------------
		UPDATE Tbl_Presecription_Info
		SET Payment_Transaction_Id = @FinalPaymentTxnId
		WHERE User_Id = @UserId
		AND Payment_Transaction_Id IS NULL;

        COMMIT TRANSACTION;

        SELECT @FinalPaymentTxnId AS PaymentTransactionId;

    END TRY
    BEGIN CATCH
        ROLLBACK TRANSACTION;
        THROW;
    END CATCH
END
