            @CouponAmount MONEY = 0,
            @FinalAmount MONEY = 0;

        /* ------------------------------
           1️⃣ Create or reuse OPEN checkout
        ------------------------------ */
        SELECT TOP 1
            @PaymentTransactionId = PaymentTransactionId
        FROM CheckOutPaymentTransactions
        WHERE UserId = @UserId
          AND OrderStatus = 'Open'
        ORDER BY CreatedOn DESC;

        IF @PaymentTransactionId IS NULL
        BEGIN
            INSERT INTO CheckOutPaymentTransactions
            (
                UserId,
                CreatedOn,
                TxnStatus,
                PaymentStatus,
                OrderStatus,
                OrderCurrentStatus,
                PaymentMode,
                CurrencyCode,
                CurrencySymbol,
                CurrencyValue
            )
            VALUES
            (
                @UserId,
                SYSDATETIME(),
                'Checkout',
                0,
                'Open',
                10,
                @PaymentMode,
                @CurrencyCode,
                @CurrencySymbol,
                @CurrencyValue
            );

            SET @PaymentTransactionId = SCOPE_IDENTITY();
        END

        /* ------------------------------
           2️⃣ Cart Subtotal
        ------------------------------ */
        SELECT
            @SubTotal = SUM(ci.UnitPrice * ci.Quantity)
        FROM CartItem ci
        INNER JOIN Cart c ON ci.CartId = c.CartId
        WHERE c.UserId = @UserId
          AND c.Status = 'ACTIVE';

        /* ------------------------------
           3️⃣ Shipping Rules (LEGACY)
        ------------------------------ */
        IF (@PaymentMode = 'Cash On Delivery')
        BEGIN
            IF (@SubTotal < 1000)
                SET @ShippingCharges = 150;
            ELSE IF (@SubTotal <= 2000)
                SET @ShippingCharges = 100;
            ELSE
                SET @ShippingCharges = 50;
        END
        ELSE
        BEGIN
            IF (@SubTotal <= 500)
                SET @ShippingCharges = 50;
            ELSE
                SET @ShippingCharges = 0;
        END

        /* ------------------------------
           4️⃣ Coupon Logic (LEGACY)
        ------------------------------ */
        IF @CouponId IS NOT NULL
        BEGIN
            SELECT
                @CouponAmount =
                    CASE
                        WHEN Coupon_Percentage = 0
                            THEN Coupon_Amount
                        ELSE ROUND((Coupon_Percentage * @SubTotal) / 100, 0)
                    END
            FROM Tbl_Coupon_Info
            WHERE Coupon_Id = @CouponId;
        END

        SET @FinalAmount = @SubTotal + @ShippingCharges - ISNULL(@CouponAmount, 0);

        /* ------------------------------
           5️⃣ Update Checkout Summary
        ------------------------------ */
        UPDATE CheckOutPaymentTransactions
        SET
            TxnAmount         = @FinalAmount,
            ShippingCharges   = @ShippingCharges,
            Promo_Code_ID     = @CouponId,
            Promo_Code_Amount = @CouponAmount,
            PaymentMode       = @PaymentMode,
            UpdatedOn         = SYSDATETIME()
        WHERE PaymentTransactionId = @PaymentTransactionId;

        /* ------------------------------
           6️⃣ Snapshot Cart → Checkout Items
        ------------------------------ */
        DELETE FROM CheckOutUserProductTransactions
        WHERE PaymentTransactionId = @PaymentTransactionId;

        INSERT INTO CheckOutUserProductTransactions
        (
            PaymentTransactionId,
            UserId,
            ProductId,
            SubProductId,
            Quantity,
            ProductCost,
            ProductDiscountPercentage,
            ProductDiscountCost,
            ShippingAddressId,
            BillingAddressId,
            IsActive,
            IsDeleted,
            CreatedOn,
            UpdatedOn,
            CreatedBy,
            UpdatedBy,
            Status,
            CurrencyCode,
            CurrencyValue,
            CurrencySymbol,
            OrdersReturnReason,
            OrdersReturnAction,
            ReplacementTransactionId,
            IsReplaced,
			ExpectedDeliveryDate
        )
        SELECT
            @PaymentTransactionId,
            @UserId,
            ci.ProductId,
            NULL,
            ci.Quantity,
            ci.UnitPrice * ci.Quantity,
            ISNULL(p.ProductDiscountPercentage, 0),
            ISNULL(p.ProductDiscountCost, 0),
            @ShippingAddressId,
            @BillingAddressId,
            1,
            0,
            SYSDATETIME(),
            SYSDATETIME(),
            @UserId,
            @UserId,
            0,
            @CurrencyCode,
            @CurrencyValue,
            @CurrencySymbol,
            NULL,
            NULL,
            0,
            0,
			@ExpectedDeliveryDate
        FROM CartItem ci
        INNER JOIN Cart c ON ci.CartId = c.CartId
        INNER JOIN Products p ON ci.ProductId = p.ProductId
        WHERE c.UserId = @UserId
          AND c.Status = 'ACTIVE';

        COMMIT TRAN;

        /* ------------------------------
           7️⃣ Return
        ------------------------------ */
        SELECT 
            @PaymentTransactionId AS PaymentTransactionId,
            @FinalAmount AS PayableAmount,
            @ShippingCharges AS ShippingCharges;

    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0 ROLLBACK TRAN;
        THROW;
    END CATCH
END
