CREATE PROCEDURE [dbo].[SP_Checkout_ConfirmCOD]
(
    @UserId BIGINT,
    @CheckoutTransactionId BIGINT
)
AS
BEGIN
    SET NOCOUNT ON;

    BEGIN TRY
        BEGIN TRAN;

        DECLARE
            @CheckoutTxnId BIGINT,
            @FinalPaymentTxnId BIGINT,
            @CouponId BIGINT,
            @CouponAmount DECIMAL(18,2),
            @HasPromo BIT,
            @SubTotal DECIMAL(18,2),
            @ShippingCharges DECIMAL(18,2),
            @FinalAmount DECIMAL(18,2),
            @IsValid BIT,
            @Err NVARCHAR(200);

        --------------------------------------------------
        -- 1️⃣ Get Checkout
        --------------------------------------------------
        SELECT TOP 1
            @CheckoutTxnId = PaymentTransactionId,
            @CouponId = Promo_Code_ID,
            @CouponAmount = ISNULL(Promo_Code_Amount, 0),
            @HasPromo = ISNULL(Has_Promo_Code, 0),
            @ShippingCharges = ISNULL(ShippingCharges, 0)
        FROM CheckOutPaymentTransactions
        WHERE UserId = @UserId
          AND PaymentTransactionId = @CheckoutTransactionId
          AND OrderStatus = 'Open';

        IF @CheckoutTxnId IS NULL
        BEGIN
            RAISERROR ('No open checkout found for COD', 16, 1);
            ROLLBACK TRAN;
            RETURN;
        END

        --------------------------------------------------
        -- 2️⃣ Subtotal
        --------------------------------------------------
        SELECT 
            @SubTotal = SUM(ProductCost)
        FROM CheckOutUserProductTransactions
        WHERE PaymentTransactionId = @CheckoutTxnId;

        IF @SubTotal IS NULL SET @SubTotal = 0;

        --------------------------------------------------
        -- 3️⃣ Coupon Engine
        --------------------------------------------------
        IF @CouponId IS NOT NULL AND @HasPromo = 1
        BEGIN
            EXEC dbo.SP_Coupon_ValidateAndApply
                @CouponId,
                @UserId,
                NULL,
                @SubTotal,
                0,
                1,
                1,
                @CheckoutTxnId,
                @IsValid OUTPUT,
                @CouponAmount OUTPUT,
                @Err OUTPUT;

            IF @IsValid = 0
            BEGIN
                SET @CouponId = NULL;
                SET @CouponAmount = 0;
                SET @HasPromo = 0;
            END
        END

        --------------------------------------------------
        -- 4️⃣ Final Amount
        --------------------------------------------------
        SET @FinalAmount = @SubTotal + @ShippingCharges - @CouponAmount;
        IF @FinalAmount < 0 SET @FinalAmount = 0;

        --------------------------------------------------
        -- 5️⃣ Create Payment
        --------------------------------------------------
        INSERT INTO PaymentTransactions
        (
            UserId,
            PaymentMode,
            TxnStatus,
            PaymentStatus,
            CreatedOn,
            CurrencyCode,
            CurrencySymbol,
            CurrencyValue,
            TxnAmount,
            TxnMessage,
            Authorized,
            OrderCurrentStatus,
            ShippingCharges,
            Has_Promo_Code,
            Promo_Code_ID,
            Promo_Code_Amount
        )
        SELECT
            UserId,
            'Cash On Delivery',
            'SUCCESS',
            1,
            SYSDATETIME(),
            CurrencyCode,
            CurrencySymbol,
            CurrencyValue,
            @FinalAmount,
            'Transaction Successful through COD',
            1,
            6,
            @ShippingCharges,
            @HasPromo,
            @CouponId,
            CASE WHEN @HasPromo = 1 THEN @CouponAmount ELSE NULL END
        FROM CheckOutPaymentTransactions
        WHERE PaymentTransactionId = @CheckoutTxnId;

        SET @FinalPaymentTxnId = SCOPE_IDENTITY();

        --------------------------------------------------
        -- 6️⃣ Move Items (FIXED)
        --------------------------------------------------
        INSERT INTO UserProductTransactions
        (
            PaymentTransactionId,
            UserId,
            ProductId,
            SubProductId,
            Quantity,
			--------------------------------------------------
			-- PRICING SNAPSHOT (CRITICAL)
			--------------------------------------------------
			ProductOriginalCost,
			ProductCost,
			ProductDiscountPercentage,
			ProductDiscountCost,
			 --------------------------------------------------
			-- ADDRESS & META
			--------------------------------------------------
			ShippingAddressId,
			BillingAddressId,
			IsActive,
			IsDeleted,
			CreatedOn,
			UpdatedOn,
			CreatedBy,
			UpdatedBy,
			Status,

            CurrencyCode,
            CurrencyValue,
            CurrencySymbol,

            OrdersReturnReason,
            OrdersReturnAction,
            ReplacementTransactionId,
            IsReplaced,

            ExpectedDeliveryDate,
			--------------------------------------------------
			-- GST
			--------------------------------------------------
			GST_Percentage,
			GST_Amount,
			CGST,
			SGST,
			IGST,
			BaseAmount
        )
        SELECT
            @FinalPaymentTxnId,
            cup.UserId,
            cup.ProductId,
            cup.SubProductId,
            cup.Quantity,
			--------------------------------------------------
			-- ✅ PRICING (LOCKED FROM CHECKOUT)
			--------------------------------------------------
			p.ProductOriginalCost,
			cup.ProductCost,
			ISNULL(cup.ProductDiscountPercentage, 0),
			ISNULL(cup.ProductDiscountCost, 0),

			--------------------------------------------------
			-- META
			--------------------------------------------------
			cup.ShippingAddressId,
			cup.BillingAddressId,
			1,
			0,
			SYSDATETIME(),
			SYSDATETIME(),
			cup.CreatedBy,
			cup.UpdatedBy,
			0,

            chk.CurrencyCode,
            chk.CurrencyValue,
            chk.CurrencySymbol,

            cup.OrdersReturnReason,
            cup.OrdersReturnAction,
            cup.ReplacementTransactionId,
            cup.IsReplaced,
            cup.ExpectedDeliveryDate,

			--------------------------------------------------
			-- ✅ GST (via function)
			--------------------------------------------------
			p.GST,
			gst.GST_Amount,
			gst.CGST,
			gst.SGST,
			gst.IGST,
			gst.BaseAmount
		FROM CheckOutUserProductTransactions cup
		INNER JOIN CheckOutPaymentTransactions chk
			ON chk.PaymentTransactionId = cup.PaymentTransactionId
		INNER JOIN Products p
			ON p.ProductId = cup.ProductId
		INNER JOIN UserAddresses ua
			ON ua.UserAddressId = cup.ShippingAddressId
		CROSS APPLY dbo.fn_CalculateGST(
			cup.ProductCost,
			p.GST,
			ua.StateName
		) gst
		WHERE cup.PaymentTransactionId = @CheckoutTxnId;

        --------------------------------------------------
        -- 7️⃣ Close Checkout
        --------------------------------------------------
        UPDATE CheckOutPaymentTransactions
        SET OrderStatus = 'Closed',
            UpdatedOn = SYSDATETIME()
        WHERE PaymentTransactionId = @CheckoutTxnId;

        --------------------------------------------------
        -- 8️⃣ Clear Cart
        --------------------------------------------------
        DELETE CI
        FROM CartItem CI
        INNER JOIN Cart C ON CI.CartId = C.CartId
        WHERE C.UserId = @UserId;

        UPDATE Cart
        SET Status = 'CHECKED_OUT',
            UpdatedOn = SYSDATETIME()
        WHERE UserId = @UserId
          AND Status = 'ACTIVE';

        --------------------------------------------------
        -- 9️⃣ Attach Prescriptions
        --------------------------------------------------
        UPDATE Tbl_Presecription_Info
        SET Payment_Transaction_Id = @FinalPaymentTxnId
        WHERE User_Id = @UserId
          AND Payment_Transaction_Id IS NULL;

        COMMIT TRAN;

        SELECT @FinalPaymentTxnId AS PaymentTransactionId;

    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0 ROLLBACK TRAN;
        THROW;
    END CATCH
END
