CREATE PROCEDURE [dbo].[SP_Cart_ApplyCoupon]
(
    @CartId BIGINT,
    @UserId BIGINT = NULL,
    @CouponCode NVARCHAR(50)
)
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE 
        @CouponId BIGINT,
        @CartTotal DECIMAL(18,2),
        @DiscountAmount DECIMAL(18,2) = 0,
        @IsValid BIT,
        @Err NVARCHAR(200);

    --------------------------------------------------
    -- 1. Get CouponId
    --------------------------------------------------
    SELECT @CouponId = Coupon_Id
    FROM Tbl_Coupon_Info
    WHERE Coupon_Code = @CouponCode
      AND Status = 1;

    IF @CouponId IS NULL
    BEGIN
        RAISERROR('Invalid coupon code', 16, 1);
        RETURN;
    END

    --------------------------------------------------
    -- 2. Calculate Cart Total
    --------------------------------------------------
    SELECT @CartTotal = SUM(Quantity * UnitPrice)
    FROM CartItem
    WHERE CartId = @CartId;

    IF @CartTotal IS NULL SET @CartTotal = 0;

    --------------------------------------------------
    -- 3. Validate via Engine
    --------------------------------------------------
    EXEC dbo.SP_Coupon_ValidateAndApply
        @CouponId = @CouponId,
        @UserId = @UserId,
        @CartId = @CartId,
        @SubTotal = @CartTotal,
        @Recalculate = 1,
        @SyncCart = 0,
        @SyncCheckout = 0,
        @CheckoutTxnId = NULL,
        @IsValid = @IsValid OUTPUT,
        @CouponAmount = @DiscountAmount OUTPUT,
        @ErrorMessage = @Err OUTPUT;

    IF @IsValid = 0
    BEGIN
        RAISERROR(@Err, 16, 1);
        RETURN;
    END

    --------------------------------------------------
    -- 4. Apply Coupon to Cart
    --------------------------------------------------
    UPDATE Cart
    SET 
        Has_Promo_Code = 1,
        Promo_Code_ID = @CouponId,
        Promo_Code_Amount = @DiscountAmount,
        UpdatedOn = SYSDATETIME()
    WHERE CartId = @CartId;

    --------------------------------------------------
    -- 5. Return Result
    --------------------------------------------------
    SELECT 
        @CartTotal AS CartTotal,
        @DiscountAmount AS DiscountAmount,
        (@CartTotal - @DiscountAmount) AS FinalAmount;
END
