CREATE   PROCEDURE [dbo].[SP_UserOtp_Save]
(
    @UserId     BIGINT,
    @OtpCode    VARCHAR(6),
    @ExpiryMin  INT = 5
)
AS
BEGIN
    SET NOCOUNT ON;

    -- Invalidate previous OTPs
    UPDATE UserOtp
    SET IsUsed = 1
    WHERE UserId = @UserId
      AND IsUsed = 0;

    INSERT INTO UserOtp
    (
        UserId,
        OtpHash,
        ExpiresAt,
        IsUsed
    )
    VALUES
    (
        @UserId,
        @OtpCode,
        DATEADD(MINUTE, @ExpiryMin, SYSUTCDATETIME()),
        0
    );
END;
