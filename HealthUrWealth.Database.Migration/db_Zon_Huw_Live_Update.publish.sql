        IF NOT EXISTS (
            SELECT 1
            FROM CheckOutPaymentTransactions
            WHERE PaymentTransactionId = @PaymentTransactionId
              AND UserId = @UserId
              AND OrderStatus = 'Open'
        )
        BEGIN
            RAISERROR ('Invalid or already processed checkout',16,1);
            ROLLBACK TRANSACTION;
            RETURN;
        END

        /* 2️⃣ Insert failed payment record */
        INSERT INTO PaymentTransactions
        (
            UserId,
            PaymentMode,
            TxnStatus,
            TxnMessage,
            PaymentStatus,
            CreatedOn,
            PGTxnId,
            CurrencyCode,
            CurrencySymbol,
            CurrencyValue,
            TxnAmount
        )
        SELECT
            UserId,
            @PaymentMode,
            'FAILED',
            'Transaction Failed through ' + @PaymentMode,
            3,  -- legacy canceled enum
            SYSDATETIME(),
            @PGTxnId,
            CurrencyCode,
            CurrencySymbol,
            CurrencyValue,
            TxnAmount
        FROM CheckOutPaymentTransactions
        WHERE PaymentTransactionId = @PaymentTransactionId;

        SET @FinalPaymentTxnId = SCOPE_IDENTITY();

        /* 3️⃣ Update checkout status */
        UPDATE CheckOutPaymentTransactions
        SET
            OrderStatus = 'Failed',
            UpdatedOn = SYSDATETIME()
        WHERE PaymentTransactionId = @PaymentTransactionId;

        COMMIT TRANSACTION;

        SELECT @FinalPaymentTxnId AS PaymentTransactionId;

    END TRY
    BEGIN CATCH
        ROLLBACK TRANSACTION;
        THROW;
    END CATCH
END
