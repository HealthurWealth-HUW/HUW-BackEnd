CREATE PROCEDURE [dbo].[SP_Checkout_UpsertAndCalculate]
(
    @UserId BIGINT,
    @PaymentMode NVARCHAR(50),
    @ShippingAddressId BIGINT,
    @BillingAddressId BIGINT,
    @ExpectedDeliveryDate DATETIME,
    @CurrencyCode NVARCHAR(10),
    @CurrencySymbol NVARCHAR(5),
    @CurrencyValue DECIMAL(18,6)
)
AS
BEGIN
    SET NOCOUNT ON;

    BEGIN TRY
        BEGIN TRAN;

        --------------------------------------------------
        -- 0. Validation
        --------------------------------------------------
        IF @ShippingAddressId IS NULL OR @BillingAddressId IS NULL
        BEGIN
            RAISERROR ('Shipping and Billing Address are mandatory', 16, 1);
            ROLLBACK TRAN;
            RETURN;
        END

        DECLARE 
            @PaymentTransactionId BIGINT,
            @CartId BIGINT,
            @SubTotal DECIMAL(18,2) = 0,
            @ShippingCharges DECIMAL(18,2) = 0,
            @CouponId BIGINT = NULL,
            @CouponAmount DECIMAL(18,2) = 0,
            @HasPromo BIT = 0,
            @FinalAmount DECIMAL(18,2) = 0,
            @IsValid BIT,
            @Err NVARCHAR(200);

        --------------------------------------------------
        -- 1. Get Cart
        --------------------------------------------------
        SELECT TOP 1
            @CartId = CartId,
            @CouponId = Promo_Code_ID,
            @HasPromo = ISNULL(Has_Promo_Code, 0)
        FROM Cart
        WHERE UserId = @UserId
          AND Status = 'ACTIVE'
        ORDER BY CreatedOn DESC;

        IF @CartId IS NULL
        BEGIN
            RAISERROR ('No active cart found', 16, 1);
            ROLLBACK TRAN;
            RETURN;
        END

        --------------------------------------------------
        -- 2. Subtotal
        --------------------------------------------------
        SELECT @SubTotal = SUM(UnitPrice * Quantity)
        FROM CartItem
        WHERE CartId = @CartId;

        IF @SubTotal IS NULL OR @SubTotal = 0
        BEGIN
            RAISERROR ('Cart is empty', 16, 1);
            ROLLBACK TRAN;
            RETURN;
        END

        --------------------------------------------------
        -- 3. Coupon via Engine
        --------------------------------------------------
        IF @CouponId IS NOT NULL AND @HasPromo = 1
        BEGIN
            EXEC dbo.SP_Coupon_ValidateAndApply
                @CouponId = @CouponId,
                @UserId = @UserId,
                @CartId = @CartId,
                @SubTotal = @SubTotal,
                @Recalculate = 1,
                @SyncCart = 1,
                @SyncCheckout = 0,
                @CheckoutTxnId = NULL,
                @IsValid = @IsValid OUTPUT,
                @CouponAmount = @CouponAmount OUTPUT,
                @ErrorMessage = @Err OUTPUT;

            IF @IsValid = 0
            BEGIN
                SET @CouponId = NULL;
                SET @CouponAmount = 0;
                SET @HasPromo = 0;
            END
            ELSE
            BEGIN
                SET @HasPromo = CASE WHEN @CouponAmount > 0 THEN 1 ELSE 0 END;
            END
        END
        ELSE
        BEGIN
            SET @CouponId = NULL;
            SET @CouponAmount = 0;
            SET @HasPromo = 0;
        END

		 --------------------------------------------------
		-- 4. Discounted Amount (important step)
		--------------------------------------------------
		DECLARE @DiscountedAmount DECIMAL(18,2);

		SET @DiscountedAmount = @SubTotal - @CouponAmount;
		IF @DiscountedAmount < 0 SET @DiscountedAmount = 0;

		--------------------------------------------------
		-- 5. Shipping (based on discounted amount)
		--------------------------------------------------

		DECLARE @TotalWeightGrams DECIMAL(18,2);

		SELECT 
			@TotalWeightGrams = SUM(ISNULL(p.Weight,0) * ci.Quantity)
		FROM CartItem ci
		INNER JOIN Products p 
			ON ci.ProductId = p.ProductId
		WHERE ci.CartId = @CartId;

		IF @TotalWeightGrams IS NULL SET @TotalWeightGrams = 0;

		SET @ShippingCharges = dbo.fn_GetShippingCharge(
			@DiscountedAmount,
			@PaymentMode,
			@TotalWeightGrams
		);

		--------------------------------------------------
		-- 5.1. Final Amount
		--------------------------------------------------
		SET @FinalAmount = @DiscountedAmount + @ShippingCharges;

        --------------------------------------------------
        -- 6. Get/Create Checkout
        --------------------------------------------------
        SELECT TOP 1
            @PaymentTransactionId = PaymentTransactionId
        FROM CheckOutPaymentTransactions
        WHERE UserId = @UserId
          AND OrderStatus = 'Open'
        ORDER BY CreatedOn DESC;

        IF @PaymentTransactionId IS NULL
        BEGIN
            INSERT INTO CheckOutPaymentTransactions
            (
                UserId, CreatedOn, TxnStatus, PaymentStatus,
                OrderStatus, OrderCurrentStatus, PaymentMode,
                CurrencyCode, CurrencySymbol, CurrencyValue
            )
            VALUES
            (
                @UserId, SYSDATETIME(), 'Checkout', 0,
                'Open', 10, @PaymentMode,
                @CurrencyCode, @CurrencySymbol, @CurrencyValue
            );

            SET @PaymentTransactionId = SCOPE_IDENTITY();
        END

        --------------------------------------------------
        -- 7. Update Checkout
        --------------------------------------------------
        UPDATE CheckOutPaymentTransactions
        SET
            TxnAmount         = @FinalAmount,
            ShippingCharges   = @ShippingCharges,
            Has_Promo_Code    = @HasPromo,
            Promo_Code_ID     = @CouponId,
            Promo_Code_Amount = CASE WHEN @HasPromo = 1 THEN @CouponAmount ELSE NULL END,
            PaymentMode       = @PaymentMode,
            UpdatedOn         = SYSDATETIME()
        WHERE PaymentTransactionId = @PaymentTransactionId;

        --------------------------------------------------
        -- 8. Snapshot Items
        --------------------------------------------------
        DELETE FROM CheckOutUserProductTransactions
        WHERE PaymentTransactionId = @PaymentTransactionId;

        INSERT INTO CheckOutUserProductTransactions
        (
            PaymentTransactionId, UserId, ProductId, SubProductId,
            Quantity, ProductCost, ProductDiscountPercentage,
            ProductDiscountCost, ShippingAddressId, BillingAddressId,
            IsActive, IsDeleted, CreatedOn, UpdatedOn,
            CreatedBy, UpdatedBy, Status,
            CurrencyCode, CurrencyValue, CurrencySymbol,
            ExpectedDeliveryDate
        )
        SELECT
            @PaymentTransactionId,
            @UserId,
            ci.ProductId,
            NULL,
            ci.Quantity,
            ci.UnitPrice * ci.Quantity,
            ISNULL(p.ProductDiscountPercentage, 0),
            ISNULL(p.ProductDiscountCost, 0),
            @ShippingAddressId,
            @BillingAddressId,
            1, 0,
            SYSDATETIME(), SYSDATETIME(),
            @UserId, @UserId, 0,
            @CurrencyCode, @CurrencyValue, @CurrencySymbol,
            @ExpectedDeliveryDate
        FROM CartItem ci
        INNER JOIN Products p ON ci.ProductId = p.ProductId
        WHERE ci.CartId = @CartId;

        COMMIT TRAN;

        --------------------------------------------------
        -- 9. Return
        --------------------------------------------------
        SELECT 
            @PaymentTransactionId AS PaymentTransactionId,
            @SubTotal AS SubTotal,
            @CouponAmount AS Discount,
            @ShippingCharges AS ShippingCharges,
            @FinalAmount AS PayableAmount,
            @HasPromo AS HasPromo;

    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0 ROLLBACK TRAN;
        THROW;
    END CATCH
END
