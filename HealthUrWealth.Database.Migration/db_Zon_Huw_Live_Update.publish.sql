CREATE FUNCTION dbo.fn_CalculateGST
(
    @Price DECIMAL(18,2),
    @GST DECIMAL(5,2),
    @StateName NVARCHAR(100)
)
RETURNS TABLE
AS
RETURN
(
    SELECT
        --------------------------------------------------
        -- GST Amount (inclusive extraction)
        --------------------------------------------------
        GST_Amount = ROUND((@Price * @GST) / (100 + @GST), 2),

        --------------------------------------------------
        -- CGST
        --------------------------------------------------
        CGST = CASE 
            WHEN LOWER(@StateName) = 'telangana'
            THEN ROUND(((@Price * @GST) / (100 + @GST)) / 2, 2)
            ELSE 0
        END,

        --------------------------------------------------
        -- SGST
        --------------------------------------------------
        SGST = CASE 
            WHEN LOWER(@StateName) = 'telangana'
            THEN ROUND(((@Price * @GST) / (100 + @GST)) / 2, 2)
            ELSE 0
        END,

        --------------------------------------------------
        -- IGST
        --------------------------------------------------
        IGST = CASE 
            WHEN LOWER(@StateName) <> 'telangana'
            THEN ROUND((@Price * @GST) / (100 + @GST), 2)
            ELSE 0
        END,

        --------------------------------------------------
        -- Base Amount
        --------------------------------------------------
        BaseAmount = ROUND(
            @Price - ((@Price * @GST) / (100 + @GST)), 
        2)
);
