CREATE PROCEDURE [dbo].[SP_UserOtp_Validate]
(
    @Mobile   VARCHAR(15),
    @OtpCode  VARCHAR(6)
)
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @UserId BIGINT = 0;

    /*
      Step 1: Resolve UserId from Mobile
      (Assumes MobileNo is stored as VARCHAR / numeric safely)
    */
    SELECT TOP 1
        @UserId = U.UserId
    FROM [dbo].[Users] U
    WHERE CONVERT(VARCHAR(15), U.MobileNo) = @Mobile
      AND U.IsActive = 1
      AND U.IsDeleted = 0;

    -- If user not found → invalid
    IF (@UserId = 0)
    BEGIN
        SELECT 0 AS UserId;
        RETURN;
    END

    /*
      Step 2: Validate OTP for this UserId
    */
    IF EXISTS
    (
        SELECT 1
        FROM [dbo].[UserOtp]
        WHERE UserId = @UserId
          AND OtpHash = @OtpCode
          AND IsUsed = 0
          AND ExpiresAt >= SYSUTCDATETIME()
    )
    BEGIN
        /*
          Step 3: Mark OTP as used (single-use)
        */
        UPDATE [dbo].[UserOtp]
        SET
            IsUsed = 1,
            ExpiresAt = SYSUTCDATETIME()
        WHERE UserId = @UserId
          AND OtpHash = @OtpCode
          AND IsUsed = 0;

        /*
          Step 4: Return UserId (SUCCESS)
        */
        SELECT @UserId AS UserId;
    END
    ELSE
    BEGIN
        /*
          Invalid / expired OTP
        */
        SELECT 0 AS UserId;
    END
END;
